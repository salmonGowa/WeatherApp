import { TriangleAlert } from 'lucide-react'
import { memo } from 'react'
import { formatDuration, formatMiles, formatTime } from '../lib/format'
import { CRITERION_LABEL, RISK_COLOR, RISK_LABEL, RISK_LEVELS } from '../lib/risk'
import { riskBadge } from '../lib/ui'
import type { PlannedRoute, PlanResponse } from '../types'

const tag = 'rounded border px-1.5 py-px text-[10.5px] font-semibold uppercase tracking-wider'

function RiskBar({ route }: { route: PlannedRoute }) {
  const total = route.risk.total_miles || 1
  return (
    <div className="flex h-2 overflow-hidden rounded bg-panel-2" aria-label="Miles by risk level">
      {RISK_LEVELS.map((lvl) => {
        const miles = route.risk.miles_by_level[lvl]
        if (miles <= 0) return null
        return (
          <span
            key={lvl}
            className="block h-full"
            style={{ width: `${(miles / total) * 100}%`, background: RISK_COLOR[lvl] }}
            title={`${RISK_LABEL[lvl]}: ${formatMiles(miles)}`}
          />
        )
      })}
    </div>
  )
}

function RiskMiles({ route }: { route: PlannedRoute }) {
  return (
    <ul className="m-0 flex list-none flex-wrap gap-x-3 gap-y-0.5 p-0 text-xs">
      {RISK_LEVELS.slice(1).map((lvl) => {
        const miles = route.risk.miles_by_level[lvl]
        return (
          <li key={lvl} className={`inline-flex items-center gap-1 ${miles > 0 ? '' : 'text-muted opacity-70'}`}>
            <i className="inline-block size-2.25 rounded-full" style={{ background: RISK_COLOR[lvl] }} />
            {RISK_LABEL[lvl]} <b>{formatMiles(miles)}</b>
          </li>
        )
      })}
    </ul>
  )
}

function Recommendation({ plan }: { plan: PlanResponse }) {
  const rec = plan.recommendation
  const best = plan.routes.find((r) => r.id === rec.route_id)!
  return (
    <div className="rounded-[10px] bg-accent-soft px-3.5 py-3">
      <div className="text-[15px]">
        Recommended: <strong>{best.name}</strong>
      </div>
      <ul className="mt-1.5 mb-0 list-disc pl-4.5 text-[12.5px]">
        {rec.comparisons.map((c) => (
          <li key={c.route_id}>
            vs Route {c.route_id}:{' '}
            {c.criterion === 'tie' ? (
              'identical risk and time'
            ) : (
              <>
                {c.phrase}{' '}
                <span className="text-muted">
                  ({CRITERION_LABEL[c.criterion]}: {fmtCriterion(c.criterion, c.best)} vs{' '}
                  {fmtCriterion(c.criterion, c.other)})
                </span>
              </>
            )}
          </li>
        ))}
      </ul>
      {rec.warning && (
        <div className="mt-2 flex items-start gap-1.5 rounded-lg bg-red-600/12 px-2.5 py-2 text-[12.5px] font-semibold text-danger">
          <TriangleAlert className="mt-px size-4 flex-none" aria-hidden />
          {rec.warning}
        </div>
      )}
    </div>
  )
}

function fmtCriterion(criterion: string, v?: number) {
  if (v === undefined) return '–'
  if (criterion === 'duration_hours') return formatDuration(v)
  if (criterion === 'average_risk') return v.toFixed(2)
  return formatMiles(v)
}

interface Props {
  plan: PlanResponse
  selectedRouteId: string | null
  onSelect: (id: string) => void
}

function RouteList({ plan, selectedRouteId, onSelect }: Props) {
  const routes = [...plan.routes].sort((a, b) => a.rank - b.rank)
  return (
    <section className="flex flex-col gap-2.5">
      <Recommendation plan={plan} />
      {routes.map((r) => {
        const selected = r.id === selectedRouteId
        return (
          <button
            key={r.id}
            type="button"
            className={`flex cursor-pointer flex-col gap-1.5 rounded-[10px] border bg-panel px-3.5 py-3 text-left transition-[border-color,box-shadow] ${
              selected ? 'border-accent ring-2 ring-accent-soft' : 'border-line hover:border-muted'
            }`}
            onClick={() => onSelect(r.id)}
            aria-pressed={selected}
          >
            <div className="flex items-center justify-between gap-2">
              <span className="inline-flex items-center gap-1.5 text-[15px] font-bold">
                {r.name}
                {r.recommended && <span className={`${tag} border-accent bg-accent text-accent-ink`}>Best</span>}
                {r.synthesized && (
                  <span className={`${tag} border-line bg-panel-2 text-muted`} title="Generated by routing through a via point">
                    via
                  </span>
                )}
              </span>
              <span className={riskBadge} style={{ '--risk': RISK_COLOR[r.risk.max_level] } as React.CSSProperties}>
                max {RISK_LABEL[r.risk.max_level]}
              </span>
            </div>
            <div className="truncate text-[12.5px] text-muted">{r.summary || 'Local roads'}</div>
            <div className="flex flex-wrap gap-3.5 text-[13px]">
              <span>
                <b>{formatDuration(r.duration_hours)}</b>
                {plan.hos_applied && r.duration_hours !== r.drive_hours && (
                  <small className="text-muted"> ({formatDuration(r.drive_hours)} driving)</small>
                )}
              </span>
              <span>{formatMiles(r.distance_miles)}</span>
              <span title="Distance-weighted mean risk, 0 = Low … 4 = No Travel">
                avg risk {r.risk.average_risk.toFixed(2)}
              </span>
            </div>
            <RiskBar route={r} />
            <RiskMiles route={r} />
            <div className="text-xs text-muted">Arrive {formatTime(r.arrival)}</div>
          </button>
        )
      })}
    </section>
  )
}

export default memo(RouteList)
